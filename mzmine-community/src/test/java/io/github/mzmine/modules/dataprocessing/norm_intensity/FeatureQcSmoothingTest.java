package io.github.mzmine.modules.dataprocessing.norm_intensity;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.concurrent.CancellationException;
import org.jetbrains.annotations.NotNull;
import org.junit.jupiter.api.Test;

class FeatureQcSmoothingTest {

  private static final String FIXTURE = "/io/github/mzmine/modules/dataprocessing/norm_intensity/"
      + "feature_qc/dunn_qc_rlsc_nonlinear.csv";

  @Test
  void fitsConstantAndLinearResponsesExactlyAtQcKnots() {
    final double[] x = coordinates(7);
    final double[] constant = {8d, 8d, 8d, 8d, 8d, 8d, 8d};
    final FeatureQcDriftNormalization.Fit constantFit = FeatureQcDriftNormalization.fit(x, constant, automatic(2), () -> false);
    assertEquals(8d, constantFit.predictClamped(3.4d), 1e-10);
    assertEquals(1, constantFit.degree());
    assertEquals(x.length, constantFit.neighborhoodSize());

    final double[] linear = values(x, value -> 10d + 2.5d * value);
    final FeatureQcDriftNormalization.Fit linearFit = FeatureQcDriftNormalization.fit(x, linear, automatic(0), () -> false);
    for (int index = 0; index < x.length; index++) {
      assertEquals(linear[index], linearFit.curve().value(x[index]), 1e-9);
    }
    assertEquals(1, linearFit.degree());
  }

  @Test
  void selectsQuadraticCandidateForQuadraticTruth() {
    final double[] x = coordinates(9);
    final double[] quadratic = values(x, value -> 4d + value * value);

    final FeatureQcDriftNormalization.Fit fit = FeatureQcDriftNormalization.fit(x, quadratic, automatic(0), () -> false);

    assertEquals(2, fit.degree());
    for (int index = 0; index < x.length; index++) {
      assertEquals(quadratic[index], fit.curve().value(x[index]), 1e-8);
    }
    assertTrue(Double.isFinite(fit.crossValidationMse()));
  }

  @Test
  void autoSelectedNonlinearFitHasFinitePredictionsAndClampsProductionBoundaries() {
    final double[] x = coordinates(11);
    final double[] nonlinear = values(x, value -> 15d + 2d * Math.sin(value * .8d) + .3d * value);

    final FeatureQcDriftNormalization.Fit fit = FeatureQcDriftNormalization.fit(x, nonlinear, automatic(2), () -> false);

    assertTrue(Double.isFinite(fit.crossValidationMse()));
    assertTrue(Double.isFinite(fit.predictClamped(4.25d)));
    assertEquals(fit.curve().value(x[0]), fit.predictClamped(-10d), 1e-12);
    assertEquals(fit.curve().value(x[x.length - 1]), fit.predictClamped(100d), 1e-12);
  }

  @Test
  void matchesIndependentPythonNonlinearRobustFixture() throws IOException {
    // Generated by generate_dunn_qc_rlsc_fixture.py, which independently implements the
    // documented LOOCV/local-polynomial/spline algorithm without invoking Java or R.
    final double[] x = coordinates(9);
    final double[] y = {14d, 15.6d, 18.4d, 18d, 20.2d, 23.9d, 24.1d, 28.5d, 30.4d};
    final FeatureQcDriftNormalization.Fit fit = FeatureQcDriftNormalization.fit(x, y, automatic(2), () -> false);
    final List<String> lines;
    try (var stream = FeatureQcSmoothingTest.class.getResourceAsStream(FIXTURE)) {
      assertTrue(stream != null);
      lines = new String(stream.readAllBytes(), StandardCharsets.UTF_8).lines().toList();
    }
    final String[] metadata = lines.getFirst().substring(2).split(";");
    assertEquals(1, Integer.parseInt(metadata[1].split("=")[1]));
    assertEquals(7, Integer.parseInt(metadata[2].split("=")[1]));
    assertEquals(Double.parseDouble(metadata[3].split("=")[1]), fit.crossValidationMse(), 1e-9);
    final double target = Double.parseDouble(metadata[4].split("=")[1]);
    assertEquals(21.455555555555556d, target, 1e-12);
    for (final String line : lines.subList(2, lines.size())) {
      final String[] fields = line.split(",");
      final double coordinate = Double.parseDouble(fields[0]);
      final double prediction = Double.parseDouble(fields[1]);
      final double factor = Double.parseDouble(fields[2]);
      assertEquals(prediction, fit.predictClamped(coordinate), 1e-8, line);
      assertEquals(factor, target / fit.predictClamped(coordinate), 1e-8, line);
    }
  }

  @Test
  void robustReweightingLimitsSingleOutlierInfluence() {
    final double[] x = coordinates(11);
    final double[] values = values(x, value -> 10d + value);
    values[5] += 80d;

    final FeatureQcDriftNormalization.Fit unweighted = FeatureQcDriftNormalization.fit(x, values, automatic(0), () -> false);
    final FeatureQcDriftNormalization.Fit robust = FeatureQcDriftNormalization.fit(x, values, automatic(2), () -> false);
    final double expected = 14d;
    assertTrue(Math.abs(robust.predictClamped(4d) - expected)
        < Math.abs(unweighted.predictClamped(4d) - expected));
  }

  @Test
  void doesNotLetAnExtremeHeldOutQcChangeRobustTrainingScale() {
    final double[] x = coordinates(9);
    // The final response is intentionally extreme. During its LOOCV fold, the training set still
    // contains the moderate response at x=4, which must remain eligible for robust reweighting.
    final double[] responses = {1d, 1.1d, .9d, 1.05d, 5d, .95d, 1.03d, .97d, 1e30d};

    final FeatureQcDriftNormalization.Fit fit = FeatureQcDriftNormalization.fit(x, responses, automatic(2), () -> false);

    assertEquals(1, fit.degree());
    assertEquals(9, fit.neighborhoodSize());
    assertEquals(1.1111111111111112e59d, fit.crossValidationMse(), 1e46d);
  }

  @Test
  void rejectsInputsWithoutACompleteCandidateAndRespondsToCancellation() {
    final double[] threePoints = {1d, 2d, 3d};
    assertThrows(IllegalArgumentException.class,
        () -> FeatureQcDriftNormalization.fit(threePoints, threePoints, automatic(0), () -> false));
    assertThrows(IllegalArgumentException.class,
        () -> FeatureQcDriftNormalization.fit(new double[]{1d, 1d, 2d, 3d}, new double[]{1d, 2d, 3d, 4d}, automatic(0), () -> false));
    assertThrows(CancellationException.class,
        () -> FeatureQcDriftNormalization.fit(coordinates(10), values(coordinates(10), value -> value + 1d), automatic(2), () -> true));
  }

  @Test
  void fixedSmoothingReproducesTheSelectedCurveWithoutCrossValidation() {
    final double[] x = coordinates(9);
    final double[] y = {14d, 15.6d, 18.4d, 18d, 20.2d, 23.9d, 24.1d, 28.5d, 30.4d};
    final var automatic = FeatureQcDriftNormalization.fit(x, y, automatic(2), () -> false);
    final var settings = new FeatureQcSettings(false, automatic.span(), automatic.degree(),
        2, 5, 10d, .5d, 0);
    final var fixed = FeatureQcDriftNormalization.fit(x, y, settings, () -> false);

    assertEquals(automatic.neighborhoodSize(), fixed.neighborhoodSize());
    assertEquals(automatic.degree(), fixed.degree());
    assertNull(fixed.crossValidationMse());
    for (double coordinate = -1d; coordinate <= 10d; coordinate += .25d) {
      assertEquals(automatic.predictClamped(coordinate), fixed.predictClamped(coordinate), 1e-12);
    }
  }

  @Test
  void fixedQuadraticFitUsesTheRequestedSettingsWithoutNeedingValidLoocvFolds() {
    final double[] x = coordinates(4);
    final double[] y = values(x, value -> 10d + value * value);
    // Four observations support this quadratic fit, but omitting one leaves too few positive
    // tricube weights for a quadratic LOOCV candidate. Fixed fitting must not run that search.
    final var settings = new FeatureQcSettings(false, 1d, 2, 0, 5, 10d, .5d, 0);
    final var fit = FeatureQcDriftNormalization.fit(x, y, settings, () -> false);
    assertEquals(2, fit.degree());
    assertEquals(4, fit.neighborhoodSize());
    assertNull(fit.crossValidationMse());
    for (int i = 0; i < x.length; i++) assertEquals(y[i], fit.predictClamped(x[i]), 1e-9);
  }

  @Test
  void fixedSpanDoesNotGainANeighborThroughFloatingPointRoundoff() {
    final double[] x = coordinates(25);
    final double[] y = values(x, value -> 100d + value);
    final var settings = new FeatureQcSettings(false, 7d / 25d, 1, 0, 5, 10d, .5d, 0);
    final var fit = FeatureQcDriftNormalization.fit(x, y, settings, () -> false);
    assertEquals(7, fit.neighborhoodSize());
    assertEquals(settings.bandwidth(), fit.span());
  }

  @Test
  void automaticSmoothingIgnoresTheStoredManualSettings() {
    final double[] x = coordinates(9);
    final double[] y = values(x, value -> 20d + value * value);
    final var defaults = FeatureQcDriftNormalization.fit(x, y, automatic(0), () -> false);
    final var otherManualSettings = new FeatureQcSettings(true, .01d, 2, 0, 5, 10d, .5d, 0);
    final var fit = FeatureQcDriftNormalization.fit(x, y, otherManualSettings, () -> false);
    assertEquals(defaults.degree(), fit.degree());
    assertEquals(defaults.neighborhoodSize(), fit.neighborhoodSize());
    assertEquals(defaults.crossValidationMse(), fit.crossValidationMse());
  }

  @Test
  void fixedSmoothingRejectsUnsupportedNeighborhoodsAndHonorsCancellation() {
    final double[] x = coordinates(9);
    final double[] y = values(x, value -> 10d + value);
    final var tooSmall = new FeatureQcSettings(false, .2d, 2, 0, 5, 10d, .5d, 0);
    assertThrows(IllegalArgumentException.class,
        () -> FeatureQcDriftNormalization.fit(x, y, tooSmall, () -> false));
    final var fixed = new FeatureQcSettings(false, .75d, 1, 2, 5, 10d, .5d, 0);
    assertThrows(CancellationException.class,
        () -> FeatureQcDriftNormalization.fit(x, y, fixed, () -> true));
  }

  private static @NotNull FeatureQcSettings automatic(final int robustness) {
    return new FeatureQcSettings(true, .75d, 1, robustness, 5, 10d, .5d, 0);
  }

  private static @NotNull double[] coordinates(final int size) {
    final double[] values = new double[size];
    for (int index = 0; index < size; index++) {
      values[index] = index;
    }
    return values;
  }

  private static @NotNull double[] values(@NotNull final double[] x,
      @NotNull final java.util.function.DoubleUnaryOperator function) {
    final double[] values = new double[x.length];
    for (int index = 0; index < x.length; index++) {
      values[index] = function.applyAsDouble(x[index]);
    }
    return values;
  }
}
